// Writes src/office/<app>/failureDocs.generated.ts for Word, Excel and PowerPoint: the sentences of
// @types/office-js that say when a method or property fails, keyed by the failing call Office reports,
// such as "Paragraph.attachToList". Run with `npm run generate:failure-docs`.

import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import prettier from "prettier";
import ts from "typescript";

const require = createRequire(import.meta.url);
const root = join(dirname(fileURLToPath(import.meta.url)), "..");

const apps = [
  { namespace: "Word", folder: "word", exportName: "wordFailureDocs" },
  { namespace: "Excel", folder: "excel", exportName: "excelFailureDocs" },
  { namespace: "PowerPoint", folder: "powerpoint", exportName: "powerPointFailureDocs" },
];

const FAILURE = /\b(fails?|throws?|thrown|exception)\b/i;
const NO_FAILURE = /\bno (error|exception)\b/i;

const typingsPath = require.resolve("@types/office-js/index.d.ts");
const typingsVersion = require("@types/office-js/package.json").version;
const source = ts.createSourceFile(typingsPath, readFileSync(typingsPath, "utf8"), ts.ScriptTarget.Latest, true);
const prettierConfig = await prettier.resolveConfig(join(root, "src"));

for (const app of apps) {
  const docs = collect(app.namespace);
  const entries = [...docs.keys()].sort().map((key) => [key, [...docs.get(key)].join(" ")]);
  const code =
    `// Generated by scripts/generateFailureDocs.mjs from @types/office-js ${typingsVersion}. Do not edit.\n\n` +
    `import type { FailureDocs } from "../shared/officeError";\n\n` +
    `/** When ${app.namespace}'s methods and properties fail, by the failing call Office reports. */\n` +
    `export const ${app.exportName}: FailureDocs = ${JSON.stringify(Object.fromEntries(entries))};\n`;
  const path = join(root, "src", "office", app.folder, "failureDocs.generated.ts");
  writeFileSync(path, await prettier.format(code, { ...prettierConfig, filepath: path }));
  console.log(`${path}: ${entries.length} calls`);
}

/** The failure sentences of every member of the namespace's classes and interfaces, by "Class.member". */
function collect(namespace) {
  const docs = new Map();
  for (const statement of source.statements) {
    if (
      !ts.isModuleDeclaration(statement) ||
      statement.name.text !== namespace ||
      !statement.body ||
      !ts.isModuleBlock(statement.body)
    ) {
      continue;
    }
    for (const declaration of statement.body.statements) {
      if ((!ts.isClassDeclaration(declaration) && !ts.isInterfaceDeclaration(declaration)) || !declaration.name) {
        continue;
      }
      for (const member of declaration.members) {
        if (!member.name || !ts.isIdentifier(member.name)) {
          continue;
        }
        const sentences = failureSentences(member);
        if (sentences.length === 0) {
          continue;
        }
        const key = `${declaration.name.text}.${member.name.text}`;
        const known = docs.get(key) ?? new Set();
        sentences.forEach((sentence) => known.add(sentence));
        docs.set(key, known);
      }
    }
  }
  return docs;
}

function failureSentences(member) {
  return ts
    .getJSDocCommentsAndTags(member)
    .filter(ts.isJSDoc)
    .flatMap((doc) => sentences(plainText(ts.getTextOfJSDocComment(doc.comment) ?? "")))
    .filter((sentence) => FAILURE.test(sentence) && !NO_FAILURE.test(sentence));
}

/** The comment with {@link} tags as their text and whitespace collapsed. */
function plainText(comment) {
  return comment
    .replace(/\{@link\s+([^}\s|]+)(?:[\s|]+([^}]*))?\}/g, (_, target, text) => text?.trim() || target)
    .replace(/\s+/g, " ")
    .trim();
}

/** Splits at a full stop followed by a space and a capital letter or backtick, so "Word.List" stays whole. */
function sentences(text) {
  return text.split(/(?<=\.)\s+(?=[A-Z`])/).filter(Boolean);
}
